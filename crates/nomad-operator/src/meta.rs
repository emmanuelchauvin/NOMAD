use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

/// Detailed audit trail guaranteeing exact experimental reproducibility.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ReproducibilityAudit {
    /// Name or identifier of the LLM model.
    pub model_name: String,
    /// Cryptographic SHA-256 hash of the exact GGUF weight file or model artifact.
    pub model_sha256: String,
    /// Version string of the inference engine (e.g. "llama.cpp b2431").
    pub engine_version: String,
    /// Stochastic sampling seed.
    pub seed: u64,
    /// Sampling temperature.
    pub temperature: f64,
    /// Sampling Top-P.
    pub top_p: f64,
    /// Full prompt dispatched to the inference engine.
    pub full_prompt: String,
    /// Exact raw text generated by the model.
    pub raw_response: String,
    /// Timestamp of generation.
    pub timestamp: DateTime<Utc>,
}

